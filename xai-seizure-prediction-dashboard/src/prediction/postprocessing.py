import numpy as np
import pandas as pd
import time
from typing import List, Tuple, Dict, Any, Optional

def smooth_probabilities(probabilities: np.ndarray, window: int = 5) -> np.ndarray:
    """Applies rolling window moving average smoothing to prediction probabilities."""
    if len(probabilities) == 0:
        return np.array([])
    if len(probabilities) < window:
        return probabilities
    return pd.Series(probabilities).rolling(window=window, center=True, min_periods=1).mean().values

def compute_seizure_intervals(predictions: np.ndarray, seq_times: np.ndarray, min_duration_sec: float = 2.0) -> List[Dict[str, Any]]:
    """
    Identifies contiguous onset and offset periods of detected ictal activity.
    """
    intervals = []
    in_seizure = False
    start_t = 0.0
    
    for pred, t in zip(predictions, seq_times):
        if pred == 1 and not in_seizure:
            in_seizure = True
            start_t = t
        elif pred == 0 and in_seizure:
            in_seizure = False
            duration = t - start_t
            if duration >= min_duration_sec:
                intervals.append({
                    "start_time": round(float(start_t), 1),
                    "end_time": round(float(t), 1),
                    "duration": round(float(duration), 1)
                })
                
    if in_seizure and len(seq_times) > 0:
        duration = seq_times[-1] - start_t
        intervals.append({
            "start_time": round(float(start_t), 1),
            "end_time": round(float(seq_times[-1]), 1),
            "duration": round(float(duration), 1)
        })
        
    return intervals

def generate_clinical_summary(
    filename: str,
    model_name: str,
    risk_score: float,
    detections: int,
    total_segments: int,
    top_channels: List[str],
    intervals: Optional[List[Dict[str, Any]]] = None,
    accuracy: Optional[float] = None
) -> str:
    """Formats a structured clinical research diagnostic summary."""
    status_str = "SEIZURE DETECTED (HIGH RISK)" if risk_score >= 0.5 else "PHYSIOLOGICAL / NON-SEIZURE (LOW RISK)"
    
    interval_desc = "None"
    if intervals and len(intervals) > 0:
        interval_desc = ", ".join([f"{item['start_time']}s - {item['end_time']}s ({item['duration']}s)" for item in intervals])
        
    biomarkers = ", ".join(top_channels) if top_channels else "None highlighted"
    acc_str = f"{accuracy:.2f}%" if accuracy is not None else "N/A (No annotation file provided)"

    report = f"""# NeuroGuard Clinical EEG Analysis Report
Generated: {time.strftime("%Y-%m-%d %H:%M:%S")}
Recording: {filename} | Neural Model: {model_name}

## 1. Diagnostic Summary
- **Classification Status:** {status_str}
- **Peak Seizure Probability:** {risk_score * 100:.2f}%
- **Total Windows Evaluated:** {total_segments}
- **Detected Ictal Segments:** {detections}
- **Ground-Truth Validation Accuracy:** {acc_str}

## 2. Temporal Biomarkers & Onset
- **Identified Seizure Windows:** {interval_desc}
- **Prominent Contributing Electrodes (SHAP):** {biomarkers}

## 3. Investigative Disclaimer
This summary is generated by deep learning models for clinical research and algorithmic verification. 
Model outputs must be correlated with board-certified clinical neurophysiologist review.
"""
    return report

